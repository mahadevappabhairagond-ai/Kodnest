# 01 - String Basics & Literals in Python
# ------------------------------------------------------------

# 1. Single quotes
text1 = 'hello'
print("Single quote string:", text1)

# 2. Double quotes
text2 = "hello python"
print("Double quote string:", text2)

# 3. Triple quotes for multi-line strings
text3 = """hello"""
print("Triple double-quote string:", text3)

text4 = '''hello'''
print("Triple single-quote string:", text4)

multi_line = """This is multiple
lines of text."""
print("Multi-line string:\n", multi_line)

# 4. String concatenation
a = "hello"
b = "World"
c = a + " " + b
print("Concatenated string:", c)
