# 05 - String Negative Indexing & Slicing Practice
# ============================================================
# Rules for Negative Slicing:
# 1. Negative indices count from the end of the string (-1 is last char).
# 2. Negative step (-1, -2, etc.) traverses the string RIGHT-TO-LEFT (backward).
# 3. If step is negative, start defaults to -1 (end) and stop defaults to beginning.
# ============================================================

