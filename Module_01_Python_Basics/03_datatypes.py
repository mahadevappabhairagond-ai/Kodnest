# 03 - Primitive Datatypes in Python
# ------------------------------------------------------------

# 1. Integer (int)
age = 21
print("age:", age, "| Type:", type(age))

# 2. Floating-point (float)
marks = 45.1
print("marks:", marks, "| Type:", type(marks))

# 3. String (str)
comment = "A"
print("comment:", comment, "| Type:", type(comment))

# 4. Boolean (bool)
has_job = False
print("has_job:", has_job, "| Type:", type(has_job))

# 5. Complex number (complex)
cnum = 3 + 7j
print("cnum:", cnum, "| Type:", type(cnum))
